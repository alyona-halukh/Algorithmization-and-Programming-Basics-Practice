n = int(input("Введіть ціле невід'ємне число: "))

print("Двійковий запис:", bin(n))
print("Число парне:", (n & 1) == 0)
print("Степінь двійки:", n > 0 and (n & (n - 1)) == 0)
print("Кількість одиничних бітів:", bin(n).count("1"))
print("Кількість нульових бітів:", bin(n).count("0"))
print("Наймолодший одиничний біт:", n & -n)
print("Зсув вліво:", n << 1)
print("Зсув вправо:", n >> 1)
print("Після перемикання останнього біта:", n ^ 1)